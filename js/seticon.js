// 设置项图标渲染：表里有 → 白色线性 SVG（底色/墨色由 CSS 统一给），没有 → 原样输出 emoji
export const setIconHTML = (v) => {
  const key = typeof v === 'string' ? v : '';   // undefined / null 一律当空，别把 undefined 吐进 HTML
  const d = SET_ICON[key];
  if (!d) return key;
  const paths = d.split('|').filter(Boolean).map((p) => `<path d="${p}"/>`).join('');
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>`;
};
